create table if not exists public.game_levels (
  id bigint generated by default as identity (start with 1900000000) primary key
    check (id between 1900000000 and 2147483647),
  author_id uuid not null references auth.users (id) on delete cascade,
  author_name text not null check (char_length(author_name) between 1 and 64),
  title text not null check (char_length(title) between 1 and 100),
  user_comment text not null default '' check (char_length(user_comment) <= 1000),
  playable_character smallint not null default 0 check (playable_character between 0 and 20),
  level_xml text not null check (octet_length(level_xml) <= 524288),
  level_record text not null check (octet_length(level_record) <= 700000),
  published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  published_at timestamptz
);

create index if not exists game_levels_published_at_idx
  on public.game_levels (published_at desc)
  where published = true;

create index if not exists game_levels_author_created_at_idx
  on public.game_levels (author_id, created_at desc);

create table if not exists public.level_ratings (
  author_id uuid not null references auth.users (id) on delete cascade,
  level_id bigint not null check (level_id between 0 and 2147483647),
  rating smallint not null check (rating between 1 and 5),
  created_at timestamptz not null default now(),
  primary key (author_id, level_id)
);

create table if not exists public.replays (
  id bigint generated by default as identity (start with 1800000000) primary key
    check (id between 1800000000 and 2147483647),
  author_id uuid not null references auth.users (id) on delete cascade,
  level_id bigint check (level_id between 0 and 2147483647),
  replay_record text not null check (octet_length(replay_record) <= 4194304),
  encrypted_meta text not null check (octet_length(encrypted_meta) <= 16384),
  encryption_iv text not null check (octet_length(encryption_iv) <= 1024),
  created_at timestamptz not null default now()
);

create index if not exists replays_author_created_at_idx
  on public.replays (author_id, created_at desc);

alter table public.game_levels enable row level security;
alter table public.level_ratings enable row level security;
alter table public.replays enable row level security;
